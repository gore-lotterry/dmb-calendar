function getPhrase(date, idx) {
  if (idx < 0) return 'Служба ещё не началась. Первое послание — 18 ноября';
  // Нет фраз после дембеля
  if (date > DMB_DATE) return null;
  const mm = String(date.getMonth() + 1).padStart(2, '0');
  const dd = String(date.getDate()).padStart(2, '0');
  const left = Math.round((DMB_DATE - date) / 86400000);
  if (BY_DATE[mm + '-' + dd]) return BY_DATE[mm + '-' + dd];
  if (BY_LEFT[left]) return BY_LEFT[left];
  if (BY_INDEX[idx]) return BY_INDEX[idx];
  return GENERIC[idx % GENERIC.length];
}
